import { arg, ensureServer, launch, VIEWPORT } from './lib/browser';

const scenario = arg('scenario', 'walking')!;
const seconds = Number(arg('seconds', '12'));
const out = arg('out', 'live.png')!;
const url = `http://localhost:5173/?scenario=${scenario}`;
const server = await ensureServer(url);
const browser = await launch();
const page = await browser.newPage({ viewport: VIEWPORT, deviceScaleFactor: 1 });
const errors: string[] = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => (m.type() === 'error' || m.type() === 'warning') && errors.push(`${m.type()}: ${m.text()}`));
await page.goto(url, { waitUntil: 'load' });
await page.waitForFunction(() => typeof window.__walk === 'function', null, { timeout: 120_000 });
await page.mouse.move(640, 400);
await page.mouse.down();
await page.mouse.move(520, 410, { steps: 20 });
await page.mouse.up();
await page.waitForTimeout(seconds * 1000);
await page.mouse.click(640, 400);
await page.keyboard.press('Escape');
await page.waitForTimeout(500);
const info = await page.evaluate('(() => { const w = window.__walk(); return { t: w.sim.t, gaze: w.sim.gaze, frames: w.frames.length, panes: w.overlay.state().items.length }; })()');
await page.screenshot({ path: out });
console.log(JSON.stringify(info));
await browser.close();
await server?.close();
for (const e of errors) console.error(e);
process.exit(errors.some((e) => !e.startsWith('warning')) ? 2 : 0);
